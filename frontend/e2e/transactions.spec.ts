import { test, expect } from '@playwright/test'

test('actuals, recurrence and planned realization reconcile once with auditable corrections', async ({ page }, testInfo) => {
  const suffix = testInfo.project.name
  const account = `Phase 2 cash ${suffix}`, salary = `Salary ${suffix}`, rent = `Rent ${suffix}`
  const rule = `Salary rule ${suffix}`, planned = `Rent event ${suffix}`
  const overflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.OWNER_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.OWNER_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Account name').fill(account)
  await page.getByLabel('Opening balance').fill('0.00')
  await page.getByLabel('Opening date').fill('2026-11-01')
  await page.getByRole('button', { name: 'Add cash account' }).click()
  await expect(page.getByText('Cash account created.', { exact: true })).toBeVisible()
  for (const [name, kind] of [[salary, 'INCOME'], [rent, 'EXPENSE']]) {
    await page.getByLabel('Category name').fill(name)
    await page.getByLabel('Category kind').selectOption(kind)
    await page.getByRole('button', { name: 'Add category', exact: true }).click()
    await expect(page.locator('.categories .account-list')).toContainText(name)
  }
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Transactions', exact: true }).click()
  await page.getByRole('link', { name: 'Recurring rules', exact: true }).click()
  await page.getByLabel('Rule name').fill(rule)
  await page.getByRole('combobox', { name: 'Direction', exact: true }).selectOption('INCOME')
  await page.getByRole('combobox', { name: 'Cash account', exact: true }).selectOption({ label: account })
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: salary })
  await page.getByLabel('Planned amount').fill('3500.00')
  await page.getByLabel('Anchor date').fill('2026-11-01')
  await page.getByLabel('Start date').fill('2026-11-01')
  await page.getByRole('button', { name: 'Create rule', exact: true }).click()
  await expect(page.locator('.history .record-list')).toContainText(rule)
  await page.getByRole('combobox', { name: 'Rule', exact: true }).selectOption({ label: rule })
  await page.getByLabel('Generate / show from').fill('2026-11-01')
  await page.getByLabel('Through', { exact: true }).fill('2026-11-03')
  await page.getByRole('button', { name: 'Generate dates' }).click()
  await expect(page.getByText('PENDING', { exact: true })).toBeVisible()
  await overflow()
  await page.getByRole('link', { name: 'Planned one-offs', exact: true }).click()
  await page.getByLabel('Planned event name').fill(planned)
  await page.getByRole('combobox', { name: 'Cash account', exact: true }).selectOption({ label: account })
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: rent })
  await page.getByLabel('Planned amount').fill('1300.00')
  await page.getByLabel('Expected date').fill('2026-11-02')
  await page.getByRole('button', { name: 'Create planned event', exact: true }).click()
  await expect(page.locator('.history .record-list')).toContainText(planned)
  async function transactions() {
    await page.getByRole('link', { name: 'Actual transactions', exact: true }).click()
    await page.getByLabel('Account filter').selectOption({ label: account })
    await page.getByLabel('From', { exact: true }).fill('2026-11-01')
    await page.getByLabel('Through / as of').fill('2026-11-03')
  }
  await transactions()
  async function actual(direction: string, category: string, amount: string, source: string, note: string) {
    await page.getByRole('button', { name: 'Record actual', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: 'Direction', exact: true }).selectOption(direction)
    await dialog.getByRole('combobox', { name: 'Cash account', exact: true }).selectOption({ label: account })
    await dialog.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: category })
    await dialog.getByRole('textbox', { name: /^Amount/ }).fill(amount)
    await dialog.getByLabel('Actual date').fill(direction === 'INCOME' ? '2026-11-01' : '2026-11-02')
    await dialog.getByLabel('Note (optional)').fill(note)
    await dialog.getByLabel('Source type').selectOption(source)
    if (source === 'recurring') {
      await dialog.getByRole('combobox', { name: 'Recurring rule', exact: true }).selectOption({ label: rule })
      const option = dialog.getByRole('combobox', { name: 'Occurrence', exact: true }).locator('option').filter({ hasText: '01.11.2026' })
      await dialog.getByRole('combobox', { name: 'Occurrence', exact: true }).selectOption((await option.getAttribute('value'))!)
    } else if (source === 'planned') {
      const option = dialog.getByRole('combobox', { name: 'Planned event', exact: true }).locator('option').filter({ hasText: planned })
      await dialog.getByRole('combobox', { name: 'Planned event', exact: true }).selectOption((await option.getAttribute('value'))!)
    }
    await dialog.getByRole('button', { name: 'Post actual', exact: true }).click()
    await expect(dialog).not.toBeVisible()
  }
  await actual('INCOME', salary, '3500.00', 'recurring', 'Salary actual ' + suffix)
  await actual('EXPENSE', rent, '1300.00', 'planned', 'Rent actual ' + suffix)
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('2.200,00')
  await page.getByRole('link', { name: 'Installments', exact: true }).click()
  await page.getByRole('link', { name: 'Create plan', exact: true }).click()
  await page.getByLabel('Plan name').fill('Phase 2 installment ' + suffix)
  await page.getByLabel('Provider / merchant').fill('Acceptance fixture')
  await page.getByLabel('Total contractual payable').fill('1200.00')
  await page.getByLabel('Number of monthly installments').fill('6')
  await page.getByLabel('First due date').fill('2026-11-15')
  await page.getByRole('button', { name: 'Create plan', exact: true }).click()
  await page.getByRole('button', { name: 'Record payment', exact: true }).click()
  await page.getByRole('dialog').getByRole('combobox', { name: 'Cash account', exact: true }).selectOption({ label: account + ' · opened 01.11.2026' })
  await page.getByRole('dialog').getByLabel('Payment amount').fill('80.00')
  await page.getByRole('dialog').getByLabel('Payment date').fill('2026-11-03')
  await page.getByRole('dialog').getByRole('button', { name: 'Record payment', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('link', { name: 'Transactions', exact: true }).click()
  await page.getByLabel('Account filter').selectOption({ label: account })
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('2.120,00')
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Cash balance as of' })).toContainText('2.120,00')
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Ordinary expenses' })).toContainText('1.300,00')
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Installment repayments' })).toContainText('80,00')
  await expect(page.locator('.actual-history li')).toHaveCount(2)
  const expense = page.locator('.actual-history li').filter({ hasText: 'EXPENSE' }).filter({ hasNotText: 'VOIDED' })
  await expense.getByRole('button', { name: 'Correct actual' }).click()
  await page.getByRole('dialog').getByRole('textbox', { name: /^Amount/ }).fill('1299.99')
  await page.getByRole('dialog').getByLabel('Correction reason').fill('Cents correction')
  await page.getByRole('dialog').getByRole('button', { name: 'Post correction' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('2.120,01')
  await expect(page.locator('.actual-history li')).toHaveCount(3)
  await expense.getByRole('button', { name: 'Void actual', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Reason', { exact: true }).fill('Reversing corrected fixture')
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm void' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('3.420,00')
  await page.getByRole('link', { name: 'Planned one-offs', exact: true }).click()
  await expect(page.locator('.history li').filter({ hasText: planned })).toContainText('PLANNED')
  await transactions()
  await actual('EXPENSE', rent, '1300.00', 'none', 'Restored rent ' + suffix)
  await page.getByRole('link', { name: 'Planned one-offs', exact: true }).click()
  await page.locator('.history li').filter({ hasText: planned }).getByRole('button', { name: 'Link existing actual' }).click()
  const existing = page.getByRole('dialog').getByLabel('Existing actual').locator('option').filter({ hasText: 'Restored rent ' + suffix })
  await page.getByRole('dialog').getByLabel('Existing actual').selectOption((await existing.getAttribute('value'))!)
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm realization' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.locator('.history li').filter({ hasText: planned })).toContainText('REALIZED')
  await transactions()
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('2.120,00')
  await overflow()
  await page.screenshot({ path: testInfo.outputPath('phase2-transactions.png'), fullPage: true })
  await page.getByRole('link', { name: 'Forecast', exact: true }).click()
  await page.getByLabel('From', { exact: true }).fill('2026-11-03')
  await page.getByLabel('Through', { exact: true }).fill('2026-11-30')
  await expect(page.getByText('Calculating cash flow…')).not.toBeVisible()
  await expect(page.getByRole('region', { name: 'Baseline summary' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Baseline monthly forecast' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Baseline monthly forecast' })).toContainText('Remaining debt')
  await expect(page.getByRole('img', { name: /Monthly cash across all accounts and remaining installment debt/ })).toBeVisible()
  await expect(page.getByText('Current cash by account')).toBeVisible()
  await expect(page.locator('.forecast-section').filter({ hasText: 'Current cash by account' })).toContainText(account)
  await expect(page.getByText('Installment due 1 · Phase 2 installment ' + suffix)).toBeVisible()
  await expect(page.locator('.forecast-section').filter({ hasText: 'Baseline sources' }).locator('li').filter({ hasText: 'Installment due 1 · Phase 2 installment ' + suffix })).toContainText('120,00')
  await expect(page.locator('.forecast-section').filter({ hasText: 'Baseline sources' })).not.toContainText(rule)
  await page.locator('.forecast-section').filter({ hasText: 'What if?' }).getByLabel('Amount (EUR)').fill('5.00')
  await page.getByLabel('Expense date').fill('2026-11-20')
  await page.getByRole('button', { name: 'Compare scenario' }).click()
  await expect(page.getByRole('region', { name: 'What-if summary' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Monthly scenario differences' })).toContainText(/[-−]5,00/)
  await overflow()
  await page.screenshot({ path: testInfo.outputPath('phase3-forecast.png'), fullPage: true })
  await page.getByLabel('Through', { exact: true }).fill('2026-12-31')
  await expect(page.locator('.forecast-section').filter({ hasText: 'Baseline sources' })).toContainText(rule)
  const expected = page.locator('.forecast-section').filter({ hasText: 'Add expected income or expense' })
  await expected.getByLabel('Source name').fill('Weekly expense ' + suffix)
  await expected.getByLabel('Income or expense').selectOption('EXPENSE')
  await expected.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: rent })
  await expected.getByLabel('Cash account (optional)').selectOption({ label: account })
  await expected.getByLabel('Schedule').selectOption('WEEKLY')
  await expected.getByLabel('Amount (EUR)').fill('10.00')
  await expected.getByLabel('First expected date / anchor').fill('2026-11-05')
  await expected.getByRole('button', { name: 'Add expected item' }).click()
  await expect(page.getByText('Recurring expectation added. No actual cash posted.')).toBeVisible()
  await expect(page.locator('.forecast-section').filter({ hasText: 'Baseline sources' })).toContainText('Weekly expense ' + suffix)
  await expected.getByLabel('Source name').fill('One-off income ' + suffix)
  await expected.getByLabel('Schedule').selectOption('ONE_OFF')
  await expected.getByRole('combobox', { name: 'Category', exact: true }).selectOption({ label: salary })
  await expected.getByLabel('Amount (EUR)').fill('50.00')
  await expected.getByLabel('Expected date').fill('2026-12-20')
  await expected.getByRole('button', { name: 'Add expected item' }).click()
  await expect(page.getByText('One-off expectation added. No actual cash posted.')).toBeVisible()
  await expect(page.locator('.forecast-section').filter({ hasText: 'Baseline sources' })).toContainText('One-off income ' + suffix)
  await page.screenshot({ path: testInfo.outputPath('phase3-future-income.png'), fullPage: true })
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Transactions', exact: true }).click()
  await page.getByLabel('Account filter').selectOption({ label: account })
  await expect(page.locator('.cash-metrics section').filter({ hasText: 'Net movement' })).toContainText('2.120,00')
})
