import { test, expect } from '@playwright/test'

test('authenticated installment flow, partial payments, void and responsive layout', async ({ page }, testInfo) => {
  const overflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  await overflow()
  await page.getByLabel('Email', { exact: true }).fill(process.env.OWNER_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.OWNER_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await expect(page.getByText('Your workspace is ready')).toBeVisible()
  await overflow()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  const name = `Browser account ${testInfo.project.name}`
  await page.getByLabel('Account name').fill(name)
  await page.getByLabel('Opening balance').fill('1000.00')
  await page.getByLabel('Opening date').fill('2020-01-01')
  await page.getByRole('button', { name: 'Add cash account' }).click()
  await expect(page.getByRole('status')).toHaveText('Cash account created.')
  await overflow()
  await page.getByRole('link', { name: 'Installments', exact: true }).click()
  if (testInfo.project.name === 'desktop') await expect(page.getByText('No installment plans yet')).toBeVisible()
  await page.getByRole('link', { name: 'Create plan', exact: true }).click()
  const plan = `Browser plan ${testInfo.project.name}`
  await page.getByLabel('Plan name').fill(plan)
  await page.getByLabel('Provider / merchant').fill('Browser acceptance fixture')
  await page.getByLabel('Total contractual payable').fill('1200.00')
  await page.getByLabel('Number of monthly installments').fill('6')
  await page.getByLabel('First due date').fill('2026-01-31')
  await overflow()
  await page.getByRole('button', { name: 'Create plan', exact: true }).click()
  await expect(page.getByRole('heading', { name: plan, exact: true })).toBeVisible()
  await expect(page.locator('tbody tr').first()).toContainText('200,00')
  await expect(page.locator('tbody tr').nth(1)).toContainText('28.02.2026')
  await expect(page.locator('tbody tr').nth(2)).toContainText('31.03.2026')
  await overflow()
  async function pay(amount: string) {
    await page.getByRole('button', { name: 'Record payment', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByLabel('Cash account').selectOption({ label: `${name} · opened 01.01.2020` })
    await dialog.getByLabel('Payment amount').fill(amount)
    await dialog.getByLabel('Payment date').fill('2026-02-01')
    await dialog.getByRole('button', { name: 'Record payment', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('status')).toContainText('Payment recorded')
  }
  await pay('80.00')
  await expect(page.locator('.metrics section').first()).toContainText('1.120,00')
  await expect(page.locator('tbody tr').first()).toContainText('120,00')
  await pay('120.00')
  await expect(page.locator('.metrics section').first()).toContainText('1.000,00')
  await expect(page.locator('tbody tr').first()).toContainText('PAID')
  await expect(page.locator('.history li')).toHaveCount(2)
  await page.locator('.history li').first().getByRole('button', { name: 'Void payment' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('tbody tr').first()).toContainText('PAID')
  await page.locator('.history li').first().getByRole('button', { name: 'Void payment' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm void' }).click()
  await expect(page.getByRole('status')).toContainText('Payment voided')
  await expect(page.locator('.metrics section').first()).toContainText('1.080,00')
  await expect(page.locator('tbody tr').first()).toContainText('80,00')
  await expect(page.locator('.history li').first()).toContainText('VOIDED')
  await overflow()
  await page.screenshot({ path: testInfo.outputPath('installment-detail.png'), fullPage: true })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sign in', exact: true })).toBeVisible()
  await expect.poll(async () => (await page.request.get('/api/v1/installments')).status()).toBe(401)
})


test('money display preserves large decimal amounts and negative cents', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill(process.env.OWNER_EMAIL!)
  await page.getByLabel('Password', { exact: true }).fill(process.env.OWNER_PASSWORD!)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  for (const [suffix, amount, display] of [['large', '99999999999999999.99', '99.999.999.999.999.999,99'], ['negative', '-0.01', '-0,01']]) {
    const name = `${testInfo.project.name} ${suffix}`
    await page.getByLabel('Account name').fill(name)
    await page.getByLabel('Opening balance').fill(amount)
    await page.getByLabel('Opening date').fill('2020-01-01')
    await page.getByRole('button', { name: 'Add cash account' }).click()
    await expect(page.locator('.account-list li').filter({ hasText: name })).toContainText(display)
  }
})
